import os
import sys

from langchain.messages import HumanMessage

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from utils.llm_pick import pick_llm
from Models.schema import (
    SQLAgentSchema,
    SQLSafetyJudgementSchema,
)
from utils.database import DatabaseUtil


llm=pick_llm('medium')  # Pick the appropriate LLM based on the complexity of the task
llm_judge=llm.with_structured_output( SQLSafetyJudgementSchema)  # Create a structured output version of the LLM for judgement tasks


sql_query="SELECT * FROM users;"
prompt= """
You are an SQL Judge for data Security. Your task is  to determine whether the SQL query is safe or not .The SQL query should only be used for data retrieval
and should not modify or delete any data in the database. You are provided with the SQL query generated by the agent and the original user question.
You need to analyze the SQL query and determine if it is safe to execute based on the user's original question. If the SQL query is safe to execute, respond with "Yes".
 If the SQL query is not safe to execute, respond with "No" and provide additional comments or feedback regarding the SQL query's safety.
 
 
 
 Here's the SQL query to evaluate:
 {sql_query}
 """

response=llm_judge.invoke(prompt.format(sql_query=sql_query)).model_dump()  # Example usage of the structured output LLM for judgement tasks
print(response)

