from typing import Literal
from pydantic import BaseModel, Field


class RouterSchema(BaseModel):
    answer: Literal["sql", "etl"] = Field(
        ...,
        description=(
            "Choose sql for database queries and "
            "etl for data extraction, transformation, or loading."
        )
    )

    comments: str = Field(
        ...,
        description="Brief explanation for the routing decision."
    )




class DataAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Conversation messages exchanged between the user and agents."
    )

    route_response: str = Field(
        default="",
        description=(
            "The router's decision indicating which agent handles the request: "
            "'sql' for database queries or 'etl' for extraction, transformation, "
            "and loading."
        )
    )