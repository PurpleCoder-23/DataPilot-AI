
from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add
from langgraph.graph.message import add_messages


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list,
        description="List of messages to be processed by the agent"
    )

    user_question: str = Field(
        default="",
        description="The original question asked by the user"
    )

    curated_query: str = Field(
        default="",
        description="Curated user query"
    )

    prompt_query_context: str = Field(
        default="",
        description="Detailed prompt with SQL database context"
    )

    is_safe: Literal["Yes", "No"] = Field(
        default="No",
        description="Whether the generated SQL query is safe to execute"
    )

    comments: str = Field(
        default="",
        description="Feedback regarding the SQL query's safety"
    )

    generated_sql_query: str = Field(
        default="",
        description="SQL query generated by the agent"
    )

    sql_query_execution_result: str = Field(
        default="",
        description="Result of executing the generated SQL query"
    )

    final_response: str = Field(
        default="",
        description="Final response generated by the agent"
    )


class JudgementSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(
        ...,
        description="Whether the generated SQL query is safe to execute"
    )

    comments: str = Field(
        default="",
        description="Additional feedback regarding SQL query safety"
    )



class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list,
        description="List of messages to be processed by the ETL agent"
    )



