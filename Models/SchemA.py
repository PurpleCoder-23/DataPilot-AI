from typing import Annotated, Literal

from pydantic import BaseModel, Field
from langgraph.graph.message import add_messages


# ---------------------------------------------------------
# SQL ANALYST STATE
# ---------------------------------------------------------

class SQLAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Messages processed by the SQL Analyst",
    )

    user_question: str = Field(
        default="",
        description="Original question asked by the user",
    )

    curated_query: str = Field(
        default="",
        description="Curated user query for SQL generation",
    )

    prompt_query_context: str = Field(
        default="",
        description="SQL prompt containing database context",
    )

    is_safe: Literal["Yes", "No"] = Field(
        default="No",
        description="Whether the generated SQL query is safe",
    )

    comments: str = Field(
        default="",
        description="Feedback regarding SQL query safety",
    )

    generated_sql_query: str = Field(
        default="",
        description="SQL query generated by the agent",
    )

    sql_query_execution_result: str = Field(
        default="",
        description="Result of SQL query execution",
    )

    final_response: str = Field(
        default="",
        description="Final response generated by the SQL Analyst",
    )


# ---------------------------------------------------------
# SQL SAFETY JUDGEMENT
# ---------------------------------------------------------

class SQLSafetyJudgementSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(
        ...,
        description="Whether the SQL query is safe to execute",
    )

    comments: str = Field(
        default="",
        description="Additional feedback regarding SQL safety",
    )


# ---------------------------------------------------------
# ETL ANALYST STATE
# ---------------------------------------------------------

class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Messages processed by the ETL Analyst",
    )


# ---------------------------------------------------------
# DATA ANALYST STATE
# ---------------------------------------------------------

class DataAnalystSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Messages processed by the Data Analyst",
    )


# ---------------------------------------------------------
# MAIN AGENT ROUTER OUTPUT
# ---------------------------------------------------------

class RouterSchema(BaseModel):
    answer: Literal["sql", "etl", "data_analysis"] = Field(
        ...,
        description=(
            "Choose sql for SQL Server database queries; "
            "etl for data extraction, transformation, or loading; "
            "data_analysis for questions about a dataset uploaded "
            "by the user, including statistics, profiling, cleaning, "
            "and data visualization."
        ),
    )

    comments: str = Field(
        ...,
        description="Brief explanation for the routing decision",
    )


# ---------------------------------------------------------
# MAIN DATA AGENT STATE
# ---------------------------------------------------------

class DataAgentSchema(BaseModel):
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Conversation messages exchanged between agents",
    )

    route_response: Literal["", "sql", "etl", "data_analysis", "general", "error"] = Field(
        default="",
        description=(
            "Allowed route values: empty, sql, etl, data_analysis, general, or error. "
            "general handles greetings and simple conversational messages; "
            "error handles router failures."
        ),
    )
